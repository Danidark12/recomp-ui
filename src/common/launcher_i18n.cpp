static bool language_is_es(const char* lang) {
    return lang && (std::strcmp(lang, "es") == 0 || std::strcmp(lang, "es-ES") == 0 ||
                    std::strcmp(lang, "es_ES") == 0);
}

static bool language_is_pt(const char* lang) {
    return lang && (std::strcmp(lang, "pt") == 0 || std::strcmp(lang, "pt-BR") == 0 ||
                    std::strcmp(lang, "pt_BR") == 0);
}

