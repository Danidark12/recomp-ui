struct FmtTok {
    bool        spec;   /* false = literal */
    char        kind;   /* 's' qualquer texto, 'd' inteiro, 'f' número */
    std::string lit;
};

static void fmt_tokenize(const char* f, std::vector<FmtTok>& out) {
    std::string lit;
    for (const char* p = f; *p; ) {
        if (*p != '%') { lit += *p++; continue; }
        if (p[1] == '%') { lit += '%'; p += 2; continue; }
        const char* q = p + 1;
        while (*q && std::strchr("-+ #0", *q)) q++;
        if (*q == '*') q++; else while (*q >= '0' && *q <= '9') q++;
        if (*q == '.') { q++; if (*q == '*') q++; else while (*q >= '0' && *q <= '9') q++; }
        while (*q && std::strchr("hlz", *q)) q++;
        char conv = *q ? *q : 's';
        if (!lit.empty()) { out.push_back({false, 0, lit}); lit.clear(); }
        char kind = (conv == 'd' || conv == 'i' || conv == 'u') ? 'd'
                  : (conv == 'f') ? 'f' : 's';
        out.push_back({true, kind, std::string()});
        p = *q ? q + 1 : q;
    }
    if (!lit.empty()) out.push_back({false, 0, lit});
}

struct Template {
    std::vector<FmtTok> en;
    std::vector<FmtTok> pt;
};

static bool tpl_match(const std::vector<FmtTok>& t, size_t ti,
                      const char* s, const char* e,
                      std::vector<std::string>& caps) {
    if (ti == t.size()) return s == e;
    const FmtTok& k = t[ti];
    if (!k.spec) {
        size_t n = k.lit.size();
        if ((size_t)(e - s) < n || std::memcmp(s, k.lit.data(), n) != 0) return false;
        return tpl_match(t, ti + 1, s + n, e, caps);
    }
    const char* lo = s;
    const char* hi = s;
    if (k.kind == 'd' || k.kind == 'f') {
        if (hi < e && (*hi == '-' || *hi == '+')) hi++;
        const char* ds = hi;
        while (hi < e && ((*hi >= '0' && *hi <= '9') || (k.kind == 'f' && *hi == '.'))) hi++;
        if (hi == ds) return false;
        lo = hi; /* números: só o casamento guloso */
    } else {
        hi = e;
    }
    for (const char* m = lo; m <= hi; ++m) {
        caps.emplace_back(s, m);
        if (tpl_match(t, ti + 1, m, e, caps)) return true;
        caps.pop_back();
    }
    return false;
}

struct PtTranslator {
    std::unordered_map<std::string, const char*> exact;
    std::vector<Template> templates;
    struct CacheEntry { bool hit; std::string out; };
    std::unordered_map<std::string, CacheEntry> cache;

    PtTranslator(const LauncherI18nEntry* table, int n) {
        for (int i = 0; i < n; ++i) {
            const char* en = table[i].english;
            if (std::strchr(en, '%')) {
                Template t;
                fmt_tokenize(en, t.en);
                fmt_tokenize(table[i].localized, t.pt);
                bool has_spec = false;
                for (auto& k : t.en) has_spec |= k.spec;
                if (has_spec) { templates.push_back(std::move(t)); continue; }
            }
            exact.emplace(en, table[i].localized);
        }
    }

    const char* exact_lookup(const std::string& s) const {
        auto it = exact.find(s);
        return it == exact.end() ? nullptr : it->second;
    }

    const CacheEntry& resolve(const char* b, const char* e) {
        std::string key(b, e);
        auto it = cache.find(key);
        if (it != cache.end()) return it->second;
        if (cache.size() > 20000) cache.clear();
        CacheEntry ce{false, std::string()};
        if (const char* x = exact_lookup(key)) {
            ce.hit = true; ce.out = x;
        } else if (key.find_first_of("0123456789") != std::string::npos ||
                   key.size() > 2) {
            std::vector<std::string> caps;
            for (const Template& t : templates) {
                caps.clear();
                if (!tpl_match(t.en, 0, b, e, caps)) continue;
                std::string out;
                size_t ci = 0;
                for (const FmtTok& k : t.pt) {
                    if (!k.spec) { out += k.lit; continue; }
                    if (ci < caps.size()) {
                        const char* tr = exact_lookup(caps[ci]);
                        out += tr ? tr : caps[ci];
                    }
                    ci++;
                }
                ce.hit = true; ce.out = std::move(out);
                break;
            }
        }
        return cache.emplace(std::move(key), std::move(ce)).first->second;
    }
};

static PtTranslator& pt_translator() {
    static PtTranslator t(kPortugueseBR,
                          (int)(sizeof(kPortugueseBR) / sizeof(kPortugueseBR[0])));
    return t;
}

