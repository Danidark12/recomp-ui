/* Escolha do idioma do launcher: launcher_language.txt ao lado do executável
 * ("en" ou "pt-BR"). Sem o arquivo: RECOMP_UI_LANG do ambiente, senão o
 * padrão de compilação (inglês). */
static std::string language_file_path() {
    std::string dir;
#if defined(_WIN32)
    wchar_t wbuf[1024];
    DWORD n = GetModuleFileNameW(nullptr, wbuf, (DWORD)(sizeof(wbuf) / sizeof(wbuf[0])));
    if (n > 0 && n < sizeof(wbuf) / sizeof(wbuf[0])) {
        char buf[4096];
        int len = WideCharToMultiByte(CP_UTF8, 0, wbuf, (int)n, buf, (int)sizeof(buf) - 1, nullptr, nullptr);
        if (len > 0) {
            dir.assign(buf, (size_t)len);
            size_t cut = dir.find_last_of("\\/");
            dir = (cut == std::string::npos) ? std::string() : dir.substr(0, cut + 1);
        }
    }
#else
    char buf[4096];
    ssize_t n = readlink("/proc/self/exe", buf, sizeof(buf) - 1);
    if (n > 0) {
        dir.assign(buf, (size_t)n);
        size_t cut = dir.find_last_of('/');
        dir = (cut == std::string::npos) ? std::string() : dir.substr(0, cut + 1);
    }
#endif
    return dir + "launcher_language.txt";
}

static FILE* open_utf8(const std::string& path, const char* mode) {
#if defined(_WIN32)
    wchar_t wpath[4096];
    wchar_t wmode[8];
    if (!MultiByteToWideChar(CP_UTF8, 0, path.c_str(), -1, wpath, 4096)) return nullptr;
    if (!MultiByteToWideChar(CP_UTF8, 0, mode, -1, wmode, 8)) return nullptr;
    return _wfopen(wpath, wmode);
#else
    return std::fopen(path.c_str(), mode);
#endif
}

static std::string& current_language() {
    static std::string lang;
    static bool loaded = false;
    if (!loaded) {
        loaded = true;
        if (FILE* f = open_utf8(language_file_path(), "rb")) {
            char buf[32] = {0};
            size_t n = std::fread(buf, 1, sizeof(buf) - 1, f);
            std::fclose(f);
            std::string v(buf, n);
            while (!v.empty() && (v.back() == '\n' || v.back() == '\r' || v.back() == ' '))
                v.pop_back();
            if (v == "en" || language_is_pt(v.c_str())) lang = v;
        }
        if (lang.empty()) {
            const char* env = std::getenv("RECOMP_UI_LANG");
            lang = (env && env[0]) ? env : RECOMP_UI_LANGUAGE;
        }
    }
    return lang;
}

